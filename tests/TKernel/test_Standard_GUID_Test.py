def test_Standard_GUID_Test_OCC669_ValidGUIDConstruction():
    for s in VALID:
        Standard_GUID(s)


def test_Standard_GUID_Test_OCC669_InvalidGUIDConstruction():
    for s in INVALID:
        with pytest.raises(Standard_Failure):
            Standard_GUID(s)


def test_Standard_GUID_Test_OCC669_GUIDFormatting():
    g1 = Standard_GUID("00000000-0000-0000-0000-000000000000")
    g2 = Standard_GUID("0000000A-000B-000C-000D-00000000000E")
    g3 = Standard_GUID("0000000a-000b-000c-000d-00000000000e")
    g4 = Standard_GUID("0000000A-000B-000C-000D-00000000000E")
    assert g2 == g4
    assert g2 == g3
    assert g1 != g2


def test_Standard_GUID_Test_ConstexprConstructionAndComparison():
    assert Standard_GUID() == Standard_GUID()
    # char16_t parameters are bound as one-character str
    g1 = Standard_GUID(0x12345678, chr(0x1234), chr(0x5678), chr(0x9ABC), 0xDE, 0xF0, 0x12, 0x34, 0x56, 0x78)
    g2 = Standard_GUID(0x12345678, chr(0x1234), chr(0x5678), chr(0x9ABC), 0xDE, 0xF0, 0x12, 0x34, 0x56, 0x78)
    g3 = Standard_GUID(0x12345678, chr(0x1234), chr(0x5678), chr(0x9ABC), 0xDE, 0xF0, 0x12, 0x34, 0x56, 0x79)
    assert g1 == g2
    assert g1.IsSame(g2)
    assert g1 != g3
    assert g1.IsNotSame(g3)

    uuid = g1.ToUUID()
    assert uuid.Data1 == 0x12345678
    assert uuid.Data2 == 0x1234
    assert uuid.Data3 == 0x5678

    from_uuid = Standard_GUID(uuid)
    assert from_uuid == g1
